def _default_global_fp_lib_table():
    """Path to KiCad's own (not this project's) global fp-lib-table --
    listing every standard KiCad footprint library (Resistor_SMD,
    Capacitor_SMD, Connector_JST, TestPoint, ...). This used to be a single
    hardcoded Windows desktop path; on any other OS (this pipeline is
    designed to run inside kicad/kicad:10.0 via Docker) os.environ.get(
    "APPDATA", <that Windows path>) still
    resolved to the Windows literal (POSIX has no APPDATA), so
    load_fp_lib_table() silently found nothing there and only the
    project's OWN fp-lib-table (1 entry) ever got merged in. Every
    standard-library FPID (R_0805, C_0805, JST_XH, TestPoint_THTPad, ...)
    then failed to resolve, and place_footprints.py silently placed only
    the handful of refs whose footprint happened to live in the project's
    own library -- 3, on this board -- instead of raising loudly. Fixed by
    branching on os.name so both environments resolve correctly; the
    KICAD10_GLOBAL_FP_LIB_TABLE override still wins over either default."""
    override = os.environ.get("KICAD10_GLOBAL_FP_LIB_TABLE")
    if override:
        return override
    if os.name == "nt":
        appdata = os.environ.get(
            "APPDATA", os.path.join(os.path.expanduser("~"), "AppData", "Roaming")
        )
        return os.path.join(appdata, "kicad", "10.0", "fp-lib-table")
    # kicad/kicad:10.0's Docker image (and a normal Linux install) keeps
    # the global table under the user config dir, XDG-style.
    config_home = os.environ.get("XDG_CONFIG_HOME", os.path.join(os.path.expanduser("~"), ".config"))
    return os.path.join(config_home, "kicad", "10.0", "fp-lib-table")


GLOBAL_FP_LIB_TABLE = _default_global_fp_lib_table()

# Footprints that already exist on the board as ordinary FOOTPRINT objects
