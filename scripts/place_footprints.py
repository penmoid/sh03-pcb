"""place_footprints.py - deterministic footprint placement + net assignment
for sh03-controller.kicad_pcb.

Run with KiCad's bundled interpreter (not system python):
  python3 scripts/place_footprints.py

Idempotent and regenerating: every run wipes all footprints EXCEPT the
mounting holes (H1-H4 -- stored as ordinary FOOTPRINT objects in the board
file, not board-graphic holes; preserved verbatim, never touched) and
rebuilds every other footprint from build/sh03.net. Export the netlist
first:
  kicad-cli sch export netlist --format kicadsexpr -o build/sh03.net sh03-controller.kicad_sch

Determinism: pcbnew mints a random UUID for every object it constructs
(FootprintLoad(), and every field/graphic/pad that comes along with it).
Loaded from a saved-and-reopened board, pcbnew's footprint container order
is itself a function of those UUID values (verified empirically -- two
placement runs that differ only in UUID text produce different
board.GetFootprints() order after LoadBoard(), which reorders the pads
route_board.py feeds into its MST/routing decisions). Every UUID this
script mints is therefore overwritten with a UUID5 derived from a fixed
namespace and a stable content key (refdes, field name, pad number, graphic
index), so re-running against the same netlist regenerates the exact same
bytes.
"""

