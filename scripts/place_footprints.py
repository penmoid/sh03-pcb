def expand_vars(uri, project_dir):
    footprints_dir = os.environ.get("KICAD10_FOOTPRINT_DIR")
    if not footprints_dir:
        if os.name == "nt":
            # python.exe lives at .../KiCad/10.0/bin/python.exe
            kicad_root = os.path.dirname(os.path.dirname(sys.executable))
            footprints_dir = os.path.join(kicad_root, "share", "kicad", "footprints")
        else:
            # system python3 lives at /usr/bin/python3 -- dirname/dirname
            # of that is "/", not a KiCad install root, so the same
            # Windows-shaped derivation silently produced "/share/kicad/
            # footprints" (missing "usr") on kicad/kicad:10.0's Docker
            # image / a normal Linux package install. Use the real
            # system-wide path directly instead of deriving it.
            footprints_dir = "/usr/share/kicad/footprints"
    uri = uri.replace("${KIPRJMOD}", project_dir)
    uri = uri.replace("${KICAD10_FOOTPRINT_DIR}", footprints_dir)
    uri = re.sub(r"\$\{([A-Za-z0-9_]+)\}", lambda m: os.environ.get(m.group(1), m.group(0)), uri)
    return uri.replace("/", os.sep)


def load_fp_lib_table(path, project_dir, seen=None):
    """Parse an fp-lib-table, returning {nickname: resolved_dir}.
    Recursively follows nested `type "Table"` entries -- KiCad's global
    table on this machine is one indirection layer around the shipped
    default library list."""
    libs = {}
    if seen is None:
        seen = set()
    path = os.path.abspath(path)
    if path in seen or not os.path.isfile(path):
        return libs
    seen.add(path)
    text = open(path, encoding="utf-8").read()
    for m in re.finditer(
        r'\(lib\s*\(name "([^"]*)"\)\s*\(type "([^"]*)"\)\s*\(uri "([^"]*)"\)', text
    ):
        name, typ, uri_ = m.groups()
        resolved = expand_vars(uri_, project_dir)
        if typ == "Table":
            libs.update(load_fp_lib_table(resolved, project_dir, seen))
        else:
            libs[name] = resolved
    return libs


def parse_netlist(path):
    """Returns (components, nets).
    components: {ref: {"value": str, "footprint": str or None}}
    nets: [{"name": str, "nodes": [(ref, pin), ...]}]
    """
    text = open(path, encoding="utf-8").read().replace("\r\n", "\n")

    components = {}
    for part in re.split(r"\n\t\t\(comp\n", text)[1:]:
        end = re.search(r"\n\t\t\)\n", part)
        block = part[: end.start()] if end else part
        ref_m = re.search(r'\(ref "([^"]+)"\)', block)
        val_m = re.search(r'\(value "([^"]*)"\)', block)
        fp_m = re.search(r'\(footprint "([^"]*)"\)', block)
        if not ref_m:
            continue
        components[ref_m.group(1)] = {
            "value": val_m.group(1) if val_m else "",
            "footprint": fp_m.group(1) if fp_m else None,
        }

    nets = []
    for part in re.split(r"\n\t\t\(net\n", text)[1:]:
        end = re.search(r"\n\t\t\)\n", part)
        block = part[: end.start()] if end else part
        name_m = re.search(r'\(name "([^"]*)"\)', block)
        nodes = re.findall(
            r'\(node\n\t\t\t\t\(ref "([^"]+)"\)\n\t\t\t\t\(pin "([^"]+)"\)', block
        )
        nets.append({"name": name_m.group(1) if name_m else "", "nodes": nodes})

    return components, nets


def main():
    if not os.path.isfile(NET_PATH):
        sys.exit(f"netlist not found: {NET_PATH} -- export it first (see module docstring)")

    components, nets = parse_netlist(NET_PATH)

    fp_libs = {}
    fp_libs.update(load_fp_lib_table(GLOBAL_FP_LIB_TABLE, PROJECT_DIR))
    fp_libs.update(load_fp_lib_table(PROJECT_FP_LIB_TABLE, PROJECT_DIR))  # project overrides global
    print(f"[place] resolved {len(fp_libs)} footprint librar(y/ies) from fp-lib-table")

    board = pcbnew.LoadBoard(PCB_PATH)

    # --- wipe all footprints except the preserved mounting holes ---
    # NOTE: KiCad 10.0.5's pcbnew python bindings corrupt PCB_IO_MGR's cached
    # plugin instance if a removed FOOTPRINT's SWIG proxy is garbage
    # collected (refcount -> 0) *before* all subsequent FootprintLoad() calls
    # are done -- FootprintLoad() then raises
    # "AttributeError: 'SwigPyObject' object has no attribute 'FootprintLoad'".
    # Reproduced deterministically; keeping every removed proxy alive in a
    # list for the script's lifetime avoids it (verified: 20/20 loads
    # succeed with this held vs. failing on the very first load without it).
    _removed_kept_alive = []
    removed = 0
    preserved_refdes_fixed = 0
    for fp in list(board.GetFootprints()):
        if fp.GetReference() in PRESERVED_REFS:
            # H1-H4 are never deleted/regenerated (see PRESERVED_REFS above),
            # but their Reference text's LAYER is normalized here on every
            # run so the silkscreen-refdes convention can't drift back via a
            # stray hand-edit of the board file: mounting-hole references are
            # documentation for assembly/fab, not something printed on the
            # physical silkscreen, so they belong on *.Fab (visible there),
            # never on *.SilkS. Only the layer is touched -- position, text
            # size and visibility are left as already saved on the board.
            ref_field = fp.Reference()
            target_layer = pcbnew.B_Fab if fp.IsFlipped() else pcbnew.F_Fab
            if ref_field.GetLayer() != target_layer:
                ref_field.SetLayer(target_layer)
                preserved_refdes_fixed += 1
            continue
        board.Remove(fp)
        _removed_kept_alive.append(fp)
        removed += 1
    print(f"[place] removed {removed} existing footprint(s) (kept {sorted(PRESERVED_REFS)})")
    if preserved_refdes_fixed:
        print(f"[place] moved {preserved_refdes_fixed} preserved ref(s) Reference text "
              f"off silkscreen onto *.Fab")

    unresolved_fpids = []
    empty_footprint_refs = []
    unplaced_refs = []          # refs not in PLACEMENT table -> parked off-board
    net_objs = {}                # net name -> NETINFO_ITEM (reused across runs by name)
    placed_footprints = {}       # ref -> FOOTPRINT

    for ref in sorted(components):
        comp = components[ref]
        fpid = comp["footprint"]
        if not fpid:
            empty_footprint_refs.append(ref)
            continue

        if ":" not in fpid:
            unresolved_fpids.append((ref, fpid, "no library nickname in FPID"))
            continue
        libname, fpname = fpid.split(":", 1)
        libdir = fp_libs.get(libname)
        if not libdir:
            unresolved_fpids.append((ref, fpid, f"library nickname '{libname}' not in fp-lib-table"))
            continue

        fp = pcbnew.FootprintLoad(libdir, fpname)
        if fp is None:
            unresolved_fpids.append((ref, fpid, f"FootprintLoad returned None from {libdir}"))
            continue

        fp.SetReference(ref)
        fp.SetValue(comp["value"])
        board.Add(fp)

        # Deterministic UUIDs: the footprint itself, its fields (Reference,
        # Value, Datasheet, Description, ...), every graphical item (silk
        # rects/polys/text -- keyed by position in the library's fixed,
        # file-order iteration since they have no other stable identity),
        # and every pad (keyed by pad number, which is stable and unique
        # within a footprint).
        set_uuid(fp, f"sh03:{ref}:footprint")
        for field in fp.GetFields():
            set_uuid(field, f"sh03:{ref}:field:{field.GetName()}")
        for idx, item in enumerate(fp.GraphicalItems()):
            set_uuid(item, f"sh03:{ref}:graphic:{idx}")
        for pad in fp.Pads():
            set_uuid(pad, f"sh03:{ref}:pad:{pad.GetNumber()}")

        if ref in PLACEMENT:
            x, y, rot, layer = PLACEMENT[ref]
        else:
            x, y = FALLBACK_XY
            rot, layer = 0, "front"
            unplaced_refs.append(ref)

        pos = pcbnew.VECTOR2I(pcbnew.FromMM(x), pcbnew.FromMM(y))
        fp.SetPosition(pos)
        if layer == "back":
            fp.Flip(pos, pcbnew.FLIP_DIRECTION_LEFT_RIGHT)
        fp.SetOrientationDegrees(rot)

        if ref == "J3":
            # J3's library-default Reference text rides along with its
            # rot-180 placement and lands overhanging the board's bottom
            # edge (DRC silk_edge_clearance). Pin it to a fixed spot clear
            # of J3's own courtyard (north of its top edge, y~75.455),
            # U1's courtyard (west of x~66.6) and J2's courtyard (east of
            # x~50.7) -- set explicitly every run so the placement stays
            # deterministic regardless of rotation.
            ref_field = fp.Reference()
            ref_field.SetVisible(True)
            ref_field.SetLayer(pcbnew.F_SilkS)
            ref_field.SetTextSize(pcbnew.VECTOR2I(pcbnew.FromMM(1.0), pcbnew.FromMM(1.0)))
            ref_field.SetTextThickness(pcbnew.FromMM(0.15))
            ref_field.SetTextAngle(pcbnew.EDA_ANGLE(0, pcbnew.DEGREES_T))
            ref_field.SetPosition(pcbnew.VECTOR2I(pcbnew.FromMM(62.0), pcbnew.FromMM(74.3)))

        elif ref in R_REF_LABEL_XY:
            # R1-R4's library-default Reference text rides along with
            # their rot-270 placement (see PLACEMENT's comment for the
            # relocation rationale) and at 2.54mm pitch lands overlapping
            # the NEIGHBOURING resistor's silkscreen/pads -- caught by a
            # real DRC run (silk_overlap + silk_over_copper, 7 warnings
            # over the baseline). Pin each one to a fixed spot clear of
            # both parts in the pair and of the courtyard behind them
            # (north of R1/R2's row for the north pair, south of R3/R4's
            # for the south pair), same fixed-every-run approach as J3.
            #
            # Layer/mirror MUST track the part's actual side (back, since
            # the 2026-08-12 all-SMD-on-back move) -- this used to
            # unconditionally force F_SilkS regardless of `layer`, which was
            # harmless while every ref in this branch was front-side but
            # would have silently left R1-R4's silkscreen refdes on the
            # FRONT while the parts themselves moved to the back. Set
            # explicitly every run, same deterministic-override rationale
            # as TextSize/TextThickness/TextAngle below, not left to
            # whatever fp.Flip() happened to set earlier in this loop.
            x, label_y = R_REF_LABEL_XY[ref]
            ref_field = fp.Reference()
            ref_field.SetVisible(True)
            ref_field.SetLayer(pcbnew.B_SilkS if layer == "back" else pcbnew.F_SilkS)
            ref_field.SetMirrored(layer == "back")
            ref_field.SetTextSize(pcbnew.VECTOR2I(pcbnew.FromMM(1.0), pcbnew.FromMM(1.0)))
            ref_field.SetTextThickness(pcbnew.FromMM(0.15))
            ref_field.SetTextAngle(pcbnew.EDA_ANGLE(0, pcbnew.DEGREES_T))
            ref_field.SetPosition(pcbnew.VECTOR2I(pcbnew.FromMM(x), pcbnew.FromMM(label_y)))

        placed_footprints[ref] = fp

    if empty_footprint_refs:
        print(f"[place] refs with empty footprint field, skipped: {empty_footprint_refs}")
    if unresolved_fpids:
        print("[place] UNRESOLVED FPIDs:")
        for ref, fpid, reason in unresolved_fpids:
            print(f"  {ref}: {fpid} -- {reason}")
    if unplaced_refs:
        print(f"[place] refs missing from PLACEMENT table, parked at {FALLBACK_XY}: {unplaced_refs}")

    # --- net assignment ---
    unmatched_pads = []  # netlist pin refs with no matching pad, or no footprint at all
    for net in nets:
        name = net["name"]
        if not name:
            continue
        for ref, pin in net["nodes"]:
            fp = placed_footprints.get(ref)
            if fp is None:
                unmatched_pads.append((ref, pin, name, "no footprint placed for this ref"))
                continue
            pad = None
            for candidate in fp.Pads():
                if candidate.GetNumber() == pin:
                    pad = candidate
                    break
            if pad is None:
                unmatched_pads.append((ref, pin, name, "pad not found on footprint"))
                continue

            ni = net_objs.get(name)
            if ni is None:
                ni = board.FindNet(name)  # reuse a net already on the board, if any
                if ni is None:
                    ni = pcbnew.NETINFO_ITEM(board, name)
                    board.Add(ni)
                net_objs[name] = ni
            pad.SetNet(ni)

    if unmatched_pads:
        print("[place] UNMATCHED pad/pin references:")
        for ref, pin, name, reason in unmatched_pads:
            print(f"  {ref} pin {pin} (net {name}): {reason}")

    # --- R/U1 escape-stub X-alignment, asserted numerically ---
    #
    # PRE_ROUTES in route_board.py depends on R1.2/R2.2 (2026-08-12: R3.1/
    # R4.1 too, once R3/R4 join the pre-route scheme's alignment
    # requirement even though they aren't PRE_ROUTES entries themselves)
    # sitting X-aligned with their target U1 pin, since that's what turns
    # each hop into a trivial straight track instead of a router search.
    # The front->back move claims (in PLACEMENT's comment) that X is
    # unchanged by the flip -- checked here against LIVE pad positions
    # instead of just trusted, so a future PLACEMENT edit that breaks the
    # alignment fails loudly here rather than surfacing as a cryptic
    # PRE_ROUTES SystemExit three pipeline stages later.
    ALIGNMENT_CHECKS = [
        ("R1", "2", "U1", "26"),
        ("R2", "2", "U1", "27"),
        ("R3", "1", "U1", "17"),
        ("R4", "1", "U1", "18"),
    ]

    def _pad_pos_mm(ref, pin):
        fp = placed_footprints.get(ref)
        if fp is None:
            return None
        for pad in fp.Pads():
            if pad.GetNumber() == pin:
                p = pad.GetPosition()
                return (pcbnew.ToMM(p.x), pcbnew.ToMM(p.y))
        return None

    alignment_failures = []
    for from_ref, from_pin, to_ref, to_pin in ALIGNMENT_CHECKS:
        a = _pad_pos_mm(from_ref, from_pin)
        b = _pad_pos_mm(to_ref, to_pin)
        if a is None or b is None:
            alignment_failures.append(
                f"{from_ref}.{from_pin}->{to_ref}.{to_pin}: pad not found "
                f"(a={a}, b={b})")
            continue
        dx = abs(a[0] - b[0])
        print(f"[place] alignment check {from_ref}.{from_pin} (x={a[0]:.4f}) "
              f"vs {to_ref}.{to_pin} (x={b[0]:.4f}): dx={dx:.4f}mm")
        if dx >= 0.05:
            alignment_failures.append(
                f"{from_ref}.{from_pin}->{to_ref}.{to_pin}: X misaligned by "
                f"{dx:.4f}mm (>=0.05mm)")

    if alignment_failures:
        raise SystemExit(
            "[place] FAILED: R/U1 escape-stub X-alignment broken:\n  " +
            "\n  ".join(alignment_failures))

    board.Save(PCB_PATH)
    print(f"[place] saved {PCB_PATH}")
    print(f"[place] placed {len(placed_footprints)} footprint(s), {len(net_objs)} net(s) touched")

    # Fail loudly instead of silently saving a mostly-empty board: this
    # used to only print "UNRESOLVED FPIDs" above and continue, so a
    # broken footprint-library path (see GLOBAL_FP_LIB_TABLE's docstring)
    # silently produced a 3-footprint board with a 0 exit code, and every
    # downstream stage (route_board.py et al.) "succeeded" against that
    # garbage without complaint.
    if unresolved_fpids:
        raise SystemExit(
            f"[place] FAILED: {len(unresolved_fpids)} FPID(s) could not be resolved "
            f"(see UNRESOLVED FPIDs above) -- the saved board is missing those "
            f"footprints entirely. Check GLOBAL_FP_LIB_TABLE / KICAD10_FOOTPRINT_DIR."
        )


if __name__ == "__main__":
    main()
