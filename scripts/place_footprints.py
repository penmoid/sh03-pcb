PRESERVED_REFS = {"H1", "H2", "H3", "H4"}

# Fixed namespace for every deterministic UUID this pipeline mints. Same
# value used (independently) in route_board.py and add_ground_pour.py --
# the key strings passed to uuid.uuid5() are already scoped per-script, so
# the namespace itself doesn't need to be shared, only stable.
UUID_NAMESPACE = uuid.UUID("25a1abba-b61d-5666-8453-b2e72c16e5ab")
# Stable namespace for deterministic object identifiers.


def stable_uuid(key):
    return str(uuid.uuid5(UUID_NAMESPACE, key))


def set_uuid(item, key):
    """Overwrite item's KIID in place. m_Uuid is exposed read-only by the
    SWIG binding, but it returns a reference to the live C++ object, and
    KIID.Clone() copies a new value into it -- verified against KiCad
    10.0.5's pcbnew bindings (direct `item.m_Uuid = ...` raises, `.Clone()`
    on the returned reference mutates the real field)."""
    item.m_Uuid.Clone(pcbnew.KIID(stable_uuid(key)))


